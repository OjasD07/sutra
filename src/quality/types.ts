import type { TestCounts } from "../tools/shell/test-counts.js";

/**
 * Quality modes trade cost for assurance:
 *  - fast: deterministic evidence only (no extra model calls); the finish
 *    gate labels criteria from observed checks but never sends work back.
 *  - balanced: evidence packet, task contract, finish gate (one bounce),
 *    alignment review, one counterexample round when code changed.
 *  - deep: everything in balanced, two bounces, two counterexample rounds,
 *    and competing patches from the initial snapshot when the first fix
 *    fails or evidence stays ambiguous.
 */
export type QualityMode = "fast" | "balanced" | "deep";

export type TaskKind = "bugfix" | "feature" | "refactor" | "question" | "other";

export type CheckKind = "test" | "command" | "baseline" | "counterexample" | "review" | "diff";

/** One observed piece of evidence. Ids are stable within a turn (c1, c2, ...). */
export interface Check {
  id: string;
  kind: CheckKind;
  summary: string;
  command?: string;
  exitCode?: number | null;
  counts?: TestCounts;
  failing?: string[];
  /** Workspace edit epoch when the check ran; fresh = after the last edit. */
  epoch: number;
  /** Generated by Sutra's verifier rather than the project: not an oracle. */
  provisional?: boolean;
  passed: boolean;
  at: string;
}

export type CriterionStatus = "passed" | "failed" | "unverified";

export interface Criterion {
  id: string;
  text: string;
  status: CriterionStatus;
  /** Check ids that support the status. */
  evidence: string[];
  note?: string;
}

export interface Hypothesis {
  id: string;
  claim: string;
  location?: string;
  supports?: string;
  contradicts?: string;
  nextCheck?: string;
  status: "open" | "confirmed" | "rejected";
}

export interface Counterexample {
  name: string;
  /** Path of the provisional test file (relative to the workspace). */
  file: string;
  content: string;
  command: string;
  why: string;
  /** Still failing against the latest patch. */
  failing: boolean;
}

export interface ReviewResult {
  verdict: "aligned" | "partial" | "misaligned" | "unknown";
  /** What the reviewer, without seeing the request, thinks the patch does. */
  inferred: string;
  gaps: string[];
}

export interface CandidateResult {
  label: string;
  hypothesis: string;
  passed: boolean;
  testsWeakened: boolean;
  counterexamplesFailing: number;
  diffLines: number;
  costUsd: number;
  sessionId: string;
  selected: boolean;
  reason: string;
}

export interface Verification {
  mode: QualityMode;
  kind: TaskKind;
  overall: "verified" | "partial" | "unverified" | "failed";
  criteria: Criterion[];
  checks: Check[];
  filesChanged: string[];
  /** Hash of the changed files' current contents (identifies the verified version). */
  treeHash: string | null;
  review?: ReviewResult;
  counterexamples: Counterexample[];
  candidates: CandidateResult[];
  hypotheses: Hypothesis[];
  bounces: number;
  /** Cost of the harness's own model calls and sub-agents this turn. */
  auxCostUsd: number;
  /** Economy experiment: which model checks were skipped because deterministic checks settled the criteria. */
  economy?: { skipped: string[]; reason: string };
}

export interface QualityLimits {
  bounces: number;
  counterexampleRounds: number;
  candidates: number;
  /** Ceiling for auxiliary spend (contract, judge, review, verifier, candidates) per turn. */
  maxAuxCostUsd: number;
  contract: boolean;
  review: boolean;
  packet: boolean;
}

export const LIMITS: Record<QualityMode, QualityLimits> = {
  fast: { bounces: 0, counterexampleRounds: 0, candidates: 0, maxAuxCostUsd: 0, contract: false, review: false, packet: false },
  balanced: { bounces: 1, counterexampleRounds: 1, candidates: 0, maxAuxCostUsd: 0.1, contract: true, review: true, packet: true },
  deep: { bounces: 2, counterexampleRounds: 2, candidates: 2, maxAuxCostUsd: 0.5, contract: true, review: true, packet: true },
};
